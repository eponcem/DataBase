-- WHERE A QUE RESTRICCIONES ESTA SUJETO EL RESULTADO
-- GROUP BY BAJO QUE CAMPO DEL SELECT ESTOY AGRUPANDO EL RESULTADO
-- HAVING RESTRICCIONES DE GRUPO A LAS QUE ESTA SUJETO EL RESULTADO
-- ORDER BY ORDENADO SEGUN UN CAMPO DE LA CLAUSULA SELECT

SELECT MAX(SALARY)
FROM OEHR_EMPLOYEES 
GROUP BY DEPARTMENT_ID 
HAVING MAX(SALARY) > 10000;

/* 
QUISIERA UN REPORTE DONDE SE BUSQUE EL SUELDO MAXIMO POR DEPARTAMENTO, SIEMPRE Y CUANDO EL SUELDO MAXIMO SEA MAYOR QUE 10000
Y LOS DEPARTAMENTOS ESTEN EN EL RANGO DEL 50 Y 90, ORDENADO POR DEPARTAMENTO DESCENDENTE, FORMATO $XXX,XXX.XX
*/

SELECT DEPARTMENT_ID AS "COD_DEPARTAMENTO", TO_CHAR(MAX(SALARY),'$999,999.99') AS "SALARIO MAXIMO"
FROM OEHR_EMPLOYEES
WHERE DEPARTMENT_ID >= 50 AND DEPARTMENT_ID <= 90
GROUP BY DEPARTMENT_ID 
HAVING MAX(SALARY) > 10000
ORDER BY DEPARTMENT_ID DESC;

--------------------------------------------------------------------------------------------------------------------------------
/* 
QUISIERA UN REPORTE QUE VISUALICE EL COD TRABAJADOR, EL NOMBRE CONCATENADO CON APELLIDO, EL NOMBRE DEL CARGO QUE TIENE , ADEMAS 
DEL NOMBRE DEL DEPARTAMENTO AL QUE PERTENECE
*/

SELECT EMPLOYEE_ID AS "COD_TRABAJADOR", CONCAT(FIRST_NAME,CONCAT(' ',LAST_NAME)), JOB_TITLE, DEPARTMENT_NAME
FROM OEHR_EMPLOYEES, OEHR_JOBS, OEHR_DEPARTMENTS

/*
FUNCIONA PERO LOS DATOS NO SON COHERENTES PORQUE SE GENERA UN PRODUCTO CARTESIANO AL NO RESPETAR LAS RESTRICCIONES
PROPIAS DEL MODELO (FK) AFECTA LA INTEGRIDAD YA QUE LOS RESULTADOS NO SON CORRECTOS 
 */

SELECT OEHR_EMPLOYEES.EMPLOYEE_ID AS "COD_TRABAJADOR",
 CONCAT(OEHR_EMPLOYEES.FIRST_NAME,CONCAT(' ',OEHR_EMPLOYEES.LAST_NAME)), OEHR_JOBS.JOB_TITLE, OEHR_DEPARTMENTS.DEPARTMENT_NAME
FROM OEHR_EMPLOYEES, OEHR_JOBS, OEHR_DEPARTMENTS
WHERE OEHR_EMPLOYEES.DEPARTMENT_ID = OEHR_DEPARTMENTS.DEPARTMENT_ID AND OEHR_EMPLOYEES.JOB_ID = OEHR_JOBS.JOB_ID 

SELECT E.EMPLOYEE_ID AS "COD_TRABAJADOR",
 CONCAT(E.FIRST_NAME,CONCAT(' ',E.LAST_NAME)), J.JOB_TITLE, D.DEPARTMENT_NAME
FROM OEHR_EMPLOYEES E, OEHR_JOBS J, OEHR_DEPARTMENTS D
WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID AND E.JOB_ID = J.JOB_ID 

