/* 
QUISIERA UN REPORTE QUE INDIQUE LO SIGUIENTE: COD_EMPLEADO, APELLIDO_EMPLEADO, NOMBRE_CONTINENTE EN EL QUE VIVE
*/
-- NO es la forma ideal ya que de por si es desordenado
SELECT EMPLOYEE_ID AS "COD_EMPLEADO", LAST_NAME AS "APELLIDO", REGION_NAME AS "NOMBRE_CONTINENTE"
FROM OEHR_EMPLOYEES E, OEHR_REGIONS R, OEHR_LOCATIONS L, OEHR_COUNTRIES CO, OEHR_DEPARTMENTS D
WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID
    AND D.LOCATION_ID = L.LOCATION_ID
    AND L.COUNTRY_ID = CO.COUNTRY_ID
    AND CO.REGION_ID = R.REGION_ID;

-- Manera correcta
-- JOIN -> Union o interseccion ON -> Punto de union
SELECT EMPLOYEE_ID AS "COD_EMPLEADO", LAST_NAME AS "APELLIDO", REGION_NAME AS "NOMBRE_CONTINENTE"
FROM OEHR_EMPLOYEES E JOIN OEHR_DEPARTMENTS D ON(E.DEPARTMENT_ID = D.DEPARTMENT_ID) 
    JOIN OEHR_LOCATIONS L ON (D.LOCATION_ID = L.LOCATION_ID) 
    JOIN OEHR_COUNTRIES CO ON(L.COUNTRY_ID = CO.COUNTRY_ID) 
    JOIN OEHR_REGIONS R ON(CO.REGION_ID = R.REGION_ID)

--------------------------------------------------------------------------------------------------------------------------------

/* 
QUISIERA VER EL COD_EMPLEADO, CONCATENADO EL NOMBRE CON EL APELLIDO, Y EL NOMBRE DEL DEPARTAMENTO AL QUE PERTENECE CADA TRABAJADOR 
*/

SELECT E.EMPLOYEE_ID AS "COD_EMPLEADO", CONCAT(E.FIRST_NAME,CONCAT(' ',E.LAST_NAME)) AS "NOMBRE COMPLETO", 
D.DEPARTMENT_NAME AS "NOMBRE DEPARTAMENTO"
FROM OEHR_EMPLOYEES E JOIN OEHR_DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)





