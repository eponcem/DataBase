SELECT MAX(SALARY) - MIN(SALARY)
FROM OEHR_EMPLOYEES;

SELECT DEPARTMENT_ID AS "COD_EMPLEADO", ROUND(AVG(SALARY),0) AS "PROM_SUELDOS"
FROM OEHR_EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY DEPARTMENT_ID ASC

--------------------------------------------------------------
-- TAREA
--------------------------------------------------------------
/*
CON LA FINALIDAD DE GENERAR PRESUPUESTO, QUISIERA MONTAR UN REPORTE QUE SE ENCARGUE DE SABER CUAL
ES EL TOTAL ACUMULADO DE LOS SUELDOS POR DEPARTAMENTO Y DE ACUERDO A SU CARGO, ORDENADO POR
DEPARTAMENTO: COD_DEPARTAMENTO, CARGO, SUMATORIA_SUELDOS, ADEMAS EL SUELDO BAJO EL SIGUIENTE FORMATO:
$XXX,XXX.XX
*/

SELECT DEPARTMENT_ID AS "COD_DEPARTAMENTO", JOB_ID AS "CARGO", 
TO_CHAR(SUM(SALARY),'$999,999.99') AS "SUMATORIA_SUELDOS", COUNT(JOB_ID) AS "CANTIDAD"
FROM OEHR_EMPLOYEES
GROUP BY DEPARTMENT_ID, JOB_ID
ORDER BY 1 ASC;

--------------------------------------------------------------
-- TAREA
--------------------------------------------------------------
/*
QUISIERA UN REPORTE DONDE SE BUSQUE EL SUELDO MAXIMO POR DEPARTAMENTO, SIEMPRE Y CUANDO, ESTE SUELDO
MAXIMO SEA MAYOR QUE , 10000.
*/

SELECT DEPARTMENT_ID AS "COD_DEPARTAMENTO", MAX(SALARY) AS "SUELDO_MAXIMO"
FROM OEHR_EMPLOYEES
WHERE SALARY > 10000
GROUP BY 1;
