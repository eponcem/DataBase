-- QUISIERA SABER CUANO¿TO LLEVA TRABAJANDO CADA EMPLEADO, EN SEMANAS. DE ACUERDO A LO SIGUIENTE:
-- COD_EMPLEADO, NOMBRE CONCATENADO CON EL APELLIDO, FECHA_CONTRATO, SEMANAS_TRABAJADAS, SIEMPRE
-- QUE PERTENEZCAN AL DEPARTAMENTENTO 50 0 80, ORDENADOS DEL QUE MENOS HA TRABAJADP AÑ QUE MAS HA
-- TRABAJO , DEBE CONSIDERAR TODOS LOS TEXTOS EN MINUSCULAS

SELECT EMPLOYEE_ID AS "COD_EMPLEADO", LOWER(CONCAT(FIRST_NAME,LAST_NAME)) AS "NOMBRE COMPLETO", DEPARTMENT_ID AS "DEPARTAMENTO", HIRE_DATE AS "FECHA CONTRATO", TRUNC((SYSDATE-HIRE_DATE)/7,0) AS "SEMAMAS TRABAJADAS"
FROM OEHR_EMPLOYEES
WHERE DEPARTMENT_ID IN(50,80)
ORDER BY 4 DESC;
