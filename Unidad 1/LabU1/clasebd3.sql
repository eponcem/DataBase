-- SUBSTR(TEXTO, POS_INI, CANTIDAD_CARACTERES)
-- PARA CALCULAR EL LARGO SE OCUPA LENGTH(TEXTO)

SELECT EMAIL,UPPER(SUBSTR(EMAIL,1,LENGTH(EMAIL)-2) || SUBSTR(EMAIL,LENGTH(EMAIL),1) || 'SQL.CL') AS EMAIL
FROM OEHR_EMPLOYEES


-- QUISIERA QUE MONTARAN UN CORREO PARA CAD TRABABAJDOR QUE MANTENGA EL SIGUIENTE PATRON:
-- PRIMERA LETRA CONCATENADO CON EL APELLIDO Y TODO LO ANTERIOR CONCATENADO CON @SQL.CL 

SELECT FIRST_NAME AS NOMBRE, LAST_NAME AS APELLIDO, UPPER(CONCAT(CONCAT(SUBSTR(FIRST_NAME,1,1),LAST_NAME),'@SQL.CL')) AS EMAIL
FROM OEHR_EMPLOYEES


-- ROUND, TRUNC Y MOD SON FUNCIONES MATEMATICAS, QUE PERMITEN SEGUN LO QUE INDICA SU NOMBRE
-- RENDODEAR VALORES, TRUNCARLOS (RECORTARLOS), Y EL MOD QUE DEVUELVE EL RESTO DE UN DIVISION

-- ROUND(VALOR_NUMERO_CON_DECIMALES, CANTIDAD_DE_DECIMALES_PARA_REDONDEO)
-- TRUNC(VALOR_NUMERO_CON_DECIMALES, CANTIDAD_DE_DECIMALES_PARA_RECORTE)
-- MOD(DIVIENDO,DIVISOR)

-- QUISIERA QUE PROBARAN LAS FUNCIONES ROUND, TRUNC Y MOD, SIN EMBARGO,
-- QUIERO QUE CONSULTEN UNA TABLA, PARA ELLO EN LA CLAUSULA FROM SE DEBE INCLUIR LA TABLA VIRTUAL DUAL
-- DEBE PROBAR EL NUMERO 45.5792 CON LAS FUNCIONES ROUND Y TRUNC MOSTRANDO 3,2,1 Y 0 DECIMALES
-- SIN EMBARGO PARA EL MOD, TIENE QUE TRABAJARSE CON LA DIVISION ENTRE
-- 54 ENTRE 3, PARA CADA EJEMPLO ROUND, O TRUNC, DEBE UTILIZAR SOLO SELECT.

--ROUND
SELECT ROUND(45.5792, 3),ROUND(45.5792, 2),ROUND(45.5792, 1), ROUND(45.5792, 0) 
FROM DUAL;

--TRUNC
SELECT TRUNC(45.5792, 3), TRUNC(45.5792, 2), TRUNC(45.5792, 1), TRUNC(45.5792, 0)
FROM DUAL;

--MOD
SELECT MOD(54,3)
FROM DUAL;

