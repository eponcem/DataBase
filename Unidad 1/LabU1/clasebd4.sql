-- QUISIERA QUE LO TRABAJADO EN LOS REQUERIMIENTOS ANTERIORES, SE UTILICE PARA RESOLVER LO SIGUIENTE
-- QUISIERA VER EL CODIGO, NOMBRE Y APELLIDO, ADEMAS DE LA FECHA DE CONTRATACION DE TODO AQUELLOS
-- TRABAJADORES QUE FUERON CONTRATADOS POSTERIOR AL AÑO 2015 (SIENDO ESTA RESTRICCION LITERAL SOLO
-- INCLUYENDO EL AÑO DE LA FECHA), Y QUE SEAN ORDENADOS POR FECHA DE CONTRATACION DE MAYOR A MENOR

SELECT EMPLOYEE_ID AS "COD_EMPLEADO", FIRST_NAME AS "NOMBRE", LAST_NAME AS "APELLIDO", TO_CHAR(HIRE_DATE,'YYYY') AS "FECHA"
FROM OEHR_EMPLOYEES
WHERE TO_NUMBER(TO_CHAR(HIRE_DATE,'YYYY'),'9999') > 2015
ORDER BY 4 ASC;


