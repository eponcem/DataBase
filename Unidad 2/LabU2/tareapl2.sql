-- CÓMO PODRÍA GENERAR UN PROCEDIMIENTO INTEGRAL, QUE SE ENCARGUE DE REALIZAR
-- LAS 3 OPERACIONES DE LOS REQUERIMIENTOS ANTERIORES EN UN SOLO PROCEDIMIENTO ALMACENADO, 
-- ESTE DEBE INCLUIR CONTROL DE CONCURRENCIA, COMO TAMBIÉN CONTROL DE TRANSACCIONES
-- Y MANEJO DE EXCEPCIONES, DE NOMBRE IUD_USUARIOS, CON SU PREFIJO CORRESPONDIENTE.
--------------------------------------------------------

CREATE OR REPLACE PROCEDURE EMPM_IUD_USUARIOS(
    OPCION_P    VARCHAR2,
    COD_USUARIO_P       NUMBER,
    NOMBRE_USUARIO_P    VARCHAR2 DEFAULT NULL,
    APELLIDO1_USUARIO_P VARCHAR2 DEFAULT NULL, 
    APELLIDO2_USUARIO_P VARCHAR2 DEFAULT NULL
)   
IS
BEGIN
    LOCK TABLE EMPM_USUARIOS IN ROW EXCLUSIVE MODE;
    IF (UPPER(OPCION_P) = 'I') THEN
        INSERT INTO EMPM_USUARIOS(COD_USUARIO, NOMBRE_USUARIO, APELLIDO1_USUARIO, APELLIDO2_USUARIO) 
        VALUES(COD_USUARIO_P, NOMBRE_USUARIO_P, APELLIDO1_USUARIO_P, APELLIDO2_USUARIO_P);

    ELSIF (UPPER(OPCION_P) = 'U') THEN
        UPDATE EMPM_USUARIOS
        SET NOMBRE_USUARIO    = NOMBRE_USUARIO_P,
            APELLIDO1_USUARIO = APELLIDO1_USUARIO_P,
            APELLIDO2_USUARIO = APELLIDO2_USUARIO_P
        WHERE COD_USUARIO = COD_USUARIO_P;

    ELSIF (UPPER(OPCION_P) = 'D') THEN
        DELETE FROM EMPM_USUARIOS
        WHERE COD_USUARIO = COD_USUARIO_P;
       
    ELSE
        RAISE_APPLICATION_ERROR(-20001, 'La opcion debe ser I,U,D.');
    END IF;
    
    COMMIT; --- BAJAR MEMORIA AL DISCO

EXCEPTION
    WHEN PROGRAM_ERROR THEN
        RAISE_APPLICATION_ERROR(-6501,'ERROR DE PROGRAMA Y/O ASIGNACION DE VARIABLES');
    WHEN STORAGE_ERROR THEN
        RAISE_APPLICATION_ERROR(-6500,'SE ACABO LA MEMORIA, O ESTA ES CORRUPTA');
    WHEN ROWTYPE_MISMATCH THEN
        RAISE_APPLICATION_ERROR(-6504,'ERROR DE ASIGNACION DE VARIABLES');
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20010,'OCURRIO UN ERROR');

    ROLLBACK; -- EVITA QUE LLEGUE A EXISTIR TODO LO QUE BAJOMOS EN EL DISCO
END;

