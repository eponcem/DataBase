-- PARA ACCEDER AL TIPO DE DATO DE UN CAMPO DE UNA TABLA, SE TRABAJA CON LA
-- SIGUIENTE INSTRUCCIÓN: NOMBRE_TABLA.NOMBRE_CAMPO%TYPE

-- SE SOLICITA UN PROCEDIMIENTO ALMACENADO QUE SE ENCARGUE DE INGRESAR DATOS A LA 
-- TABLA USUARIO, DE NOMBRE CARGA_USUARIOS, QUE INCLUYA CONTROL DE CONCURRENCIA

CREATE OR REPLACE PROCEDURE CACB_CARGA_USUARIOS(
	COD_USUARIO_P NUMBER,
	NOMBRE_USUARIO_P VARCHAR2,
	APELLIDO1_USUARIO_P VARCHAR2, 
	APELLIDO2_USUARIO_P VARCHAR2
)	
IS
BEGIN
	-- LOCK TABLE NOMBRE_TABLA IN MODO_BLOQUEO MODE; -- CONTROL DE CONCURRENCIA
	LOCK TABLE CACB_USUARIO IN ROW EXCLUSIVE MODE;
	INSERT INTO CACB_USUARIO(COD_USUARIO, NOMBRE_USUARIO, APELLIDO1_USUARIO, APELLIDO2_USUARIO) 
	VALUES(COD_USUARIO_P, NOMBRE_USUARIO_P,APELLIDO1_USUARIO_P, APELLIDO2_USUARIO_P);
END;


