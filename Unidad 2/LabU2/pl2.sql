-- MODIFICAR EL PROCEDIMIENTO ALMACENADO ANTERIOR, E INCLUIR CONTROL DE TRANSACCIONES

CREATE OR REPLACE PROCEDURE CACB_CARGA_USUARIOS(
	COD_USUARIO_P NUMBER,
	NOMBRE_USUARIO_P VARCHAR2,
	APELLIDO1_USUARIO_P VARCHAR2, 
	APELLIDO2_USUARIO_P VARCHAR2
)	
IS
BEGIN
	LOCK TABLE CACB_USUARIO IN ROW EXCLUSIVE MODE;

	INSERT INTO CACB_USUARIO(COD_USUARIO, NOMBRE_USUARIO, APELLIDO1_USUARIO, APELLIDO2_USUARIO) 
	VALUES(COD_USUARIO_P, NOMBRE_USUARIO_P,APELLIDO1_USUARIO_P, APELLIDO2_USUARIO_P);

	COMMIT;--- BAJAR MEMORIA AL DISCO
	EXCEPTION
		WHEN PROGRAM_ERROR THEN
			RAISE_APPLICATION_ERROR(-6501,'ERROR DE PROGRAMA Y/O ASIGNACION DE VARIABLES');
		WHEN STORAGE_ERROR THEN
			RAISE_APPLICATION_ERROR(-6500,'SE ACABO LA MEMORIA, O ESTA ES CORRUPTA');
		WHEN ROWTYPE_MISMATCH THEN
			RAISE_APPLICATION_ERROR(-6504,'ERROR DE ASIGNACION DE VARIABLES');
		WHEN OTHERS THEN
			RAISE_APPLICATION_ERROR(-20010,'OCURRIO UN ERROR');
		ROLLBACK; -- EVITA QUE LLEGUE A EXISTIR TODO LO QUE BAJOMOS EN EL DISCO
END;



-- EJECUCIÓN DEL PA
BEGIN
	DELETE FROM CACB_USUARIO;
	CACB_CARGA_USUARIOS(1,'CARLOS','CASTRO','BUSTAMANTE');
	CACB_CARGA_USUARIOS(2,'JUAN','SOLER','GARCIA');
	CACB_CARGA_USUARIOS(3,'MACARENA', 'URBINA', 'FIGUEROA');
	CACB_CARGA_USUARIOS(4,'JOSE', 'REYES', 'CASTRO');
END;

-- VALIDAR QUE FUNCIONA EL PA

SELECT * FROM CACB_USUARIO;


