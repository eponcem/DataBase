-- PRIMARIA PARA LA TABLA DETALLE DE NOTAS Y OTRO PARA LA TABLA USUARIOS
-- TRABAJADA EN CLASES ANTERIORES. (RECORDAR QUE HASTA LA CLASE ANTERIOR
-- ESTO LO HICIMOS CON SECUENCIAS Y LUEGO CON FUNCIONES).
-- TAMBIÉN DEBE GENERAR OTRO TRIGGER QUE SE ENCARGUE DE TRABAJAR LOS 
-- CAMPOS DE TIPO TEXTO EVALUÁNDOLOS EN MAYÚSCULA PARA LA TABLA USUARIOS.
-- LOS NOMBRES DE LOS TRIGGER SERÁN CON SUS PREFIJO CORRESPONDIENTES:
-- PK_AUTO_XXX, DONDE XXX DEBERÁ SER REEMPLAZADO POR EL NOMBRE DE LA TABLA
-- CON LA QUE TRABAJA. Y PARA LAS MAYÚSCULAS DEBE SER MAY_USUARIO


-- LUEGO DE RESOLVER LA TAREA 1
-- SE PIDE TRABAJAR EN ACTUALIZAR EL PROCEDIMIENTO ALMACENADO DE 
-- CARGA DE USUARIOS (PARA LA TABLA USUARIOS) Y QUITAR LA CLAVE PRIMARIA DEL
-- PROCEDIMIENTO COMO TAL Y DE SU INSERT ASOCIADO, PARA LUEGO REALIZAR
-- INSERCIÓN DE DATOS Y REALIZAR LA PRUEBA CORRESPONDIENTE // CON EL TRIGGER YA FUNCIONAL.

CREATE SEQUENCE EMPM_NRO_DETALLE
START WITH 2
INCREMENT BY 1;


CREATE OR REPLACE TRIGGER EMPM_PK_AUTO_DETALLES_NOTAS
BEFORE INSERT 
ON EMPM_DETALLES_NOTAS
FOR EACH ROW
BEGIN
    :NEW.NRO_DETALLE := EMPM_NRO_DETALLE.NEXTVAL;
END;

CREATE OR REPLACE TRIGGER EMPM_PK_AUTO_USUARIOS
BEFORE INSERT 
ON EMPM_USUARIOS
FOR EACH ROW
BEGIN
    :NEW.COD_USUARIO := EMPM_COD_USUARIO.NEXTVAL;
END;



CREATE OR REPLACE TRIGGER EMPM_MAY_USUARIO
BEFORE INSERT
ON EMPM_USUARIOS
FOR EACH ROW
BEGIN
    :NEW.NOMBRE_USUARIO := UPPER(:NEW.NOMBRE_USUARIO);
    :NEW.APELLIDO1_USUARIO := UPPER(:NEW.APELLIDO1_USUARIO);
    :NEW.APELLIDO2_USUARIO := UPPER(:NEW.APELLIDO2_USUARIO);
    :NEW.EMAIL_USUARIO := UPPER(:NEW.EMAIL_USUARIO);
END;



CREATE OR REPLACE PROCEDURE EMPM_CARGA_USUARIOS(
    NOMBRE_USUARIO_P VARCHAR2,
    APELLIDO1_USUARIO_P VARCHAR2,
    APELLIDO2_USUARIO_P VARCHAR2
)
IS
BEGIN
    LOCK TABLE EMPM_USUARIOS IN ROW EXCLUSIVE MODE;

    INSERT INTO EMPM_USUARIOS(
        NOMBRE_USUARIO,
        APELLIDO1_USUARIO,
        APELLIDO2_USUARIO,
        EMAIL_USUARIO
    )
    VALUES(
        NOMBRE_USUARIO_P,
        APELLIDO1_USUARIO_P,
        APELLIDO2_USUARIO_P,
        CONCAT(SUBSTR(NOMBRE_USUARIO_P, 1, 2),
            CONCAT(SUBSTR(APELLIDO1_USUARIO_P, 3, 2),
                CONCAT('.', CONCAT(APELLIDO2_USUARIO_P, '@TESTSQL.CL'))))
    );

    COMMIT;
END;