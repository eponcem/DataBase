/*
CREAR UNA TABLA DE NOMBRE DETALLES_NOTAS, CON SUS PREFIJOS CORRESPONDIENTES, Y LOS SIGUIENTES CAMPOS:
NRO_DETALLE, NOTA1, NOTA2, NOTA3, PROMEDIO, CON TODOS ELLOS DE TIPO NUMBER 
Y RESTRICCION PRIMARIA EN EL NRO_DETALLE
*/

CREATE TABLE EMPM_DETALLES_NOTAS(
    NRO_DETALLE NUMBER,
    NOTA1 NUMBER,
    NOTA2 NUMBER,
    NOTA3 NUMBER,
    PROMEDIO NUMBER,
    CONSTRAINT NDETALLE_P PRIMARY KEY (NRO_DETALLE)
);

INSERT INTO EMPM_DETALLES_NOTAS(NRO_DETALLE,NOTA1,NOTA2,NOTA3,PROMEDIO) VALUES (1,5,6,3,2.5)

/*
CREAR UN TRIGGER QUE FUNCIONE CUANDO REALICE UN INSERT EN LA TABLA RECIEN CREADA, QUE SE ENCARGUE DE GENERAR
DE FORMA :AUTOMATICA EL PROMERIO LINEAL :NEW LAS NOTAS. ESTO, PARA QUE NO SEA NECESARIO AGREGAR EL VALOR DEL
PROMEDIO EN EL INSERT ASOCIADO. Y ESTE SE CALCULE SOLO. DE NOMBRE PROMEDIO_AUTO CON SU PREFIJO CORRESPONDIENTE
*/

CREATE OR REPLACE TRIGGER EMPM_PROMEDIO_AUTO
BEFORE INSERT
ON EMPM_DETALLES_NOTAS
FOR EACH ROW
DECLARE PROMEDIO_T NUMBER;
BEGIN
    PROMEDIO_T := (:NEW.NOTA1 + :NEW.NOTA2 + :NEW.NOTA3) / 3
    :NEW.PROMEDIO := PROMEDIO_T;
END;

