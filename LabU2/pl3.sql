-----------------------------------------------

CREATE SEQUENCE NOMBRE_SECUENCIA
    START WITH NUMBERO_ENTERO
    MAXVALUE NUMBERO_ENTERO
    MINVALUE NUMBERO_ENTERO
    INCREMENT BY NUMBERO_ENTERO
    NOCYCLE;    ----- CYCLE o  NOCYCLE dependiendo de lo que queramos hacer


----- ESTIMAR EL MAX_VALUE 



CREATE SEQUENCE EMPM_COD_USUARIO
    START WITH 1
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 3500
    CACHE 200
    NOCYCLE;    ----- CYCLE o  NOCYCLE dependiendo de lo que queramos hacer


CREATE OR REPLACE PROCEDURE EMPM_CARGA_USUARIOS(
	NOMBRE_USUARIO_P VARCHAR2,
	APELLIDO1_USUARIO_P VARCHAR2, 
	APELLIDO2_USUARIO_P VARCHAR2
)	
IS
BEGIN
	-- LOCK TABLE NOMBRE_TABLA IN MODO_BLOQUEO MODE; -- CONTROL DE CONCURRENCIA
	LOCK TABLE EMPM_USUARIOS IN ROW EXCLUSIVE MODE;
	INSERT INTO EMPM_USUARIOS(COD_USUARIO, NOMBRE_USUARIO, APELLIDO1_USUARIO, APELLIDO2_USUARIO) 
	VALUES(EMPM_COD_USUARIO.NEXTVAL, NOMBRE_USUARIO_P,APELLIDO1_USUARIO_P, APELLIDO2_USUARIO_P);
END;

-- EMPM_COD_USUARIO.NEXTVAL --> PARA LLAMAR UNA SECUENCIA