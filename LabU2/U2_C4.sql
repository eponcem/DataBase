-- CREAR UNA TABLA DE NOMBRE DETALLE_NOTAS, CON SUS PREFIJOS CORRESPONDIENTES, Y LOS 
-- SIGUIENTES CAMPOS: NRO_DETALLE, NOTA1, NOTA2, NOTA3, PROMEDIO, CON TODOS ELLOS DE
-- TIPO NUMBER Y RESTRICCIÓN PRIMARIA EN EL NRO_DETALLE.

CREATE TABLE CACB_DETALLE_NOTAS(
	NRO_DETALLE NUMBER,
	NOTA1 NUMBER,
	NOTA2 NUMBER,
	NOTA3 NUMBER,
	PROMEDIO NUMBER,
	CONSTRAINT PK_CACB_DETALLE_NOTAS PRIMARY KEY(NRO_DETALLE)
);


-- REALIZAR UN INSERT A ESTA TABLA

INSERT INTO CACB_DETALLE_NOTAS(NRO_DETALLE,NOTA1,NOTA2,NOTA3,PROMEDIO)
	VALUES(1,5,6,3,2.5);


-- CREAR UN TRIGGER QUE FUNCIONE CUANDO SE REALICE UN INSERT EN LA 
-- TABLA RECIÉN CREADA, QUE SE ENCARGUE DE GENERAR DE FORMA :AUTOMÁTICA 
-- EL PROMEDIO LINEAL. ESTO, PARA QUE NO SEA NECESARIO 
-- AGREGAR EL VALOR DEL PROMEDIO EN EL INSERT ASOCIADO. Y ESTE SE 
-- CALCULE SOLO. DE NOMBRE PROMEDIO_AUTO CON SU PREFIJO CORRESPONDIENTE

CREATE OR REPLACE TRIGGER CACB_PROMEDIO_AUTO
BEFORE INSERT
ON CACB_DETALLE_NOTAS
FOR EACH ROW
DECLARE PROMEDIO_T NUMBER;
BEGIN
	PROMEDIO_T := (:NEW.NOTA1+:NEW.NOTA2+:NEW.NOTA3)/3;
	:NEW.PROMEDIO := PROMEDIO_T;
END;


INSERT INTO CACB_DETALLE_NOTAS(NRO_DETALLE,NOTA1,NOTA2,NOTA3)
	VALUES(2,5,6,3);

-- CUANDO EL CAMPO NI VALOR SE DECLARAN EN UN INSERT, ESTE
-- SE ASUME NULO. Y PARA EVITAR ESTA SITUACIÓN LLEVANDO EL CONTROL
-- ES QUE EL TRIGGER ES QUIEN DEBERÍA RESOLVER EL 
-- PROBLEMA.

CREATE OR REPLACE TRIGGER CACB_PROMEDIO_AUTO
BEFORE INSERT
ON CACB_DETALLE_NOTAS
FOR EACH ROW
DECLARE PROMEDIO_T NUMBER;
BEGIN
	PROMEDIO_T := (:NEW.NOTA1+:NEW.NOTA2+:NEW.NOTA3)/3;
	:NEW.PROMEDIO := ROUND(PROMEDIO_T,1);
END;


-- REALIZAR UN INSERT A ESTA TABLA LUEGO DE CREADO EL TRIGGER.
