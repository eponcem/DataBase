-- DE ACUERDO A LO SOLICITADO POR EL REQUERIMIENTO DE LA LÁMINA "CLASE 2"

-- GENERA LA SECUENCIA

-- ESTUDIANTES: DEBEN SER CAPACES INDEPENDIENTE DE LA FLEXIBILIDAD QUE SE OTORGUE,
-- DE ESTIMAR EL MAX_VALUE.

-- SE DEBE GENERAR UNA SECUENCIA QUE SE ENCARGUE DE ENTREGAR LOS CÓDIGOS DE USUARIO,
-- CONSIDERANDO QUE ESTE CÓDIGO ES CLAVE PRIMARIA, POR ELLO EL CÓDIGO ENTREGADO NO DEBE
-- REPERTIRSE NI QUEDAR NULO, LA SECUENCIA DEBE ESTAR A SU NOMBRE Y LLEVAR EXPLICITAMENTE
-- EL NOMBRE PARTICULAR: COD_USUARIO

/*
	LOS ESTUDIANTES DEBERÁN SER CAPACES DE ESTIMAR EL MAX VALUE DE ACUERDO AL CASO 
	EN CUESTIÓN.
	PARA EL REQUERIMIENTO QUE ESTÁ TRABAJANDO ACTUALMENTE HABLAMOS DE USUARIOS,
	SIN EMBARGO, NO SE HA ESPECIFICADO QUÉ SISTEMA ES EL ASOCIADO, POR ELLO OCUPARÉ UN 
	SUPUESTO: SE ESTIMA QUE EL SISTEMA GENERARÁ USUARIOS PARA LA CARRERA DE ICI/ECI
	600+1000+PROYECCION A 10 AÑOS, ENTIENDO 600 COMO LA MATRICULA ACTUAL, 1000 ESTUDIANTES
	ANTIGUOS SE HAYAN TITULADO O NO Y LA PROYECCION A 10 AÑOS, CONSIDERANDO INGRESO DE 
	150+5% ANUAL

	BASE DE LA SUMA EN UN MAX_VALUE VA SER DADA POR LA SIGUIENTE FORMULA:
		MAX_VALUE = 1000+600+(10*(150+(150*0,05)))
		MAX_VALUE = 3175 // CONVENGAMOS UNA APROXIMACIÓN A CODIGOS PERDIDOS, 
		REDONDEANDO ESTE MAX_VALUE EN 3500 A 10 AÑOS
*/


CREATE SEQUENCE CACB_COD_USUARIO
	START WITH 1
	INCREMENT BY 1
	MINVALUE 1
	MAXVALUE 3500
	CACHE 200 
	NOCYCLE;

--- SE MEZCLA EL PA CON LA SECUENCIA

CREATE OR REPLACE PROCEDURE CACB_CARGA_USUARIOS(
	NOMBRE_USUARIO_P VARCHAR2,
	APELLIDO1_USUARIO_P VARCHAR2,
	APELLIDO2_USUARIO_P VARCHAR2
)
IS
BEGIN
	LOCK TABLE CACB_USUARIOS IN ROW EXCLUSIVE MODE;

	INSERT INTO CACB_USUARIOS(COD_USUARIO, NOMBRE_USUARIO, APELLIDO1_USUARIO, APELLIDO2_USUARIO)
		VALUES(CACB_COD_USUARIO.NEXTVAL, NOMBRE_USUARIO_P, APELLIDO1_USUARIO_P, APELLIDO2_USUARIO_P);
	COMMIT;
	EXCEPTION
		WHEN PROGRAM_ERROR THEN
			RAISE_APPLICATION_ERROR(-6501,'ERROR DE PROGRAMA Y/O ASIGNACION DE VARIABLES');
		WHEN STORAGE_ERROR THEN
			RAISE_APPLICATION_ERROR(-6500,'SE ACABO LA MEMORIA, O ES CORRUPTA');
		WHEN ROWTYPE_MISMATCH THEN
			RAISE_APPLICATION_ERROR(-6504,'ERROR DE ASIGNACION DE VARIABLES');
		WHEN OTHERS THEN
			RAISE_APPLICATION_ERROR(-20010,'UPSI FALLÉ :(');
	ROLLBACK;
END;

-- EJECUCIÓN DEL PA
BEGIN
	DELETE FROM CACB_USUARIOS;
	CACB_CARGA_USUARIOS('CARLOS','CASTRO','BUSTAMANTE');
	CACB_CARGA_USUARIOS('JUAN','SOLER','GARCIA');
	CACB_CARGA_USUARIOS('MACARENA', 'URBINA', 'FIGUEROA');
	CACB_CARGA_USUARIOS('JOSE', 'REYES', 'CASTRO');
END;

--- SE COMPILA Y PRUEBA PA

SELECT * FROM CACB_USUARIOS;