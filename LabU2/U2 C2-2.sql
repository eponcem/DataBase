-- SE SOLITA CREAR UNA FUNCIÓN QUE RECIBA COMO PARÁMETRO UN CÓDIGO DE 
-- TRABAJADOR Y RETORNE SU SUELDO ASOCIADO (ESQUEMA HR), DEBE ESTAR A SU NOMBRE
-- Y ESPECIFICAMENTE DEBE LLAMARSE SUELDO_TRABAJADOR

CREATE OR REPLACE FUNCTION CACB_SUELDO_TRABAJADOR(
	EMPLOYEE_ID_F NUMBER
)
	RETURN NUMBER
IS
	SUELDO NUMBER;
BEGIN
	SUELDO := (SELECT SALARY
				FROM OEHR_EMPLOYEES
				WHERE EMPLOYEE_ID = EMPLOYEE_ID_F);	

	RETURN SUELDO;
END;


