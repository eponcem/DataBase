CREATE OR REPLACE FUNCTION CACB_GENERA_EMAIL(
	NOMBRE_USUARIO_F VARCHAR2,
	APELLIDO1_USUARIO_F VARCHAR2,
	APELLIDO2_USUARIO_F VARCHAR2
)
RETURN VARCHAR2
IS
	CORREO VARCHAR2(50);
BEGIN
	CORREO := CONCAT(SUBSTR(NOMBRE_USUARIO_F,1,2),CONCAT(SUBSTR(APELLIDO1_USUARIO_F, 3,2),CONCAT('.',CONCAT(APELLIDO2_USUARIO_F,'@TESTSQ.CL'))));
	RETURN CORREO;
END;

-- MODIFICAR SU PROCEDIMIENTO ALMACENADO DE CARGA DE DATOS, 
-- INCORPORANDO DENTRO DE LA CARGA DE DATOS EL CORREO 
-- LUEGO REALIZAR UN DELETE FROM A LA TABLA SIN 
-- RESTRICCIONES LIMPIARLA Y LUEGO UN LLAMADO AL PROCEDIMIENTO 
-- ALMACENADO PARA LA CARGA DE UN REGISTRO DONDE SE UTILICE LA 
-- FUNCIÓN.

CREATE OR REPLACE PROCEDURE CACB_CARGA_USUARIOS(
	NOMBRE_USUARIO_P VARCHAR2,
	APELLIDO1_USUARIO_P VARCHAR2,
	APELLIDO2_USUARIO_P VARCHAR2
)
IS
	EMAIL_P VARCHAR2(50);
BEGIN
	LOCK TABLE CACB_USUARIOS IN ROW EXCLUSIVE MODE;	

	EMAIL_P := CACB_GENERA_EMAIL(NOMBRE_USUARIO_P, APELLIDO1_USUARIO_P, APELLIDO2_USUARIO_P);

	INSERT INTO CACB_USUARIOS(COD_USUARIO, NOMBRE_USUARIO, APELLIDO1_USUARIO, APELLIDO2_USUARIO,EMAIL_USUARIO)
		VALUES(CACB_COD_USUARIO.NEXTVAL, NOMBRE_USUARIO_P, APELLIDO1_USUARIO_P, APELLIDO2_USUARIO_P,EMAIL_P);
	COMMIT;
	EXCEPTION
		WHEN PROGRAM_ERROR THEN
			RAISE_APPLICATION_ERROR(-6501,'ERROR DE PROGRAMA Y/O ASIGNACION DE VARIABLES');
		WHEN STORAGE_ERROR THEN
			RAISE_APPLICATION_ERROR(-6500,'SE ACABO LA MEMORIA, O ES CORRUPTA');
		WHEN ROWTYPE_MISMATCH THEN
			RAISE_APPLICATION_ERROR(-6504,'ERROR DE ASIGNACION DE VARIABLES');
		WHEN OTHERS THEN
			RAISE_APPLICATION_ERROR(-20010,'UPSI FALLÉ :(');
	ROLLBACK;
END;


