-- ASOCIADO,DEBE RETORNAR UN 0 Y SI NO EXISTE EMPLEADO, DEBE RETORNAR 
-- UN -1


-- PARA INCORPORAR LO ANTERIORMENTE INDICADO, DEBE TRABAJARSE DE LA 
-- SIGUIENTE FORMA:

CREATE OR REPLACE FUNCTION CACB_SUELDO_TRABAJADOR(
	EMPLOYEE_ID_F NUMBER
)
	RETURN NUMBER
IS
	SUELDO NUMBER;
BEGIN
	SELECT SALARY INTO SUELDO
	FROM OEHR_EMPLOYEES
	WHERE EMPLOYEE_ID = EMPLOYEE_ID_F;	

	IF(SUELDO IS NULL)THEN
		RETURN 0;
	ELSE
		RETURN SUELDO;
	END IF;
	
	EXCEPTION
		WHEN NO_DATA_FOUND THEN
			RETURN -1;
END;

