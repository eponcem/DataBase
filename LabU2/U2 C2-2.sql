-- CREAR UNA FUNCIÓN QUE SE ENCARGUE DE REALIZAR LA CARGA DE REGISTROS 
-- PARA LAS CLAVES PRIMARIAS DE CARACTER AUTOINCREMENTAL.

CREATE OR REPLACE FUNCTION CACB_PK_CODIGO
RETURN NUMBER
IS
	COD_USUARIO_F NUMBER;
BEGIN
	
	SELECT MAX(COD_USUARIO)+1 INTO COD_USUARIO_F
	FROM CACB_USUARIOS;

	IF(COD_USUARIO_F IS NULL)THEN
		COD_USUARIO_F := 1;
	END IF;

	RETURN COD_USUARIO_F;
END;

