-- PROCEDIMIENTOS ALMACENADOS-

-- PARA TRABAJAR EN ELLOS, SE REQUIERE CREAR UNA TABLA.

-- PASO UNO, CREARÁN UNA TABLA DE NOMBRE USUARIO A SU NOMBRE, CON SUS PREFIJOS 
-- CORRESPONDIENTES, QUE CONSIDERE COD_USUARIO DE TIPO NUMÉRICO, NOMBRE_USUARIO, 
-- APELLIDO1_USUARIO, APELLIDO2_USUARIO ESTOS ÚLTIMOS DE TIPO ALFANUMÉRICOS
-- CON 25 CARACTERES CADA UNO. DESCRIBIENDO SU CLAVE PRIMARIA EN EL COD_USUARIO.

CREATE TABLE CACB_USUARIO(
	COD_USUARIO NUMBER,
	NOMBRE_USUARIO VARCHAR2(25),
	APELLIDO1_USUARIO VARCHAR2(25),
	APELLIDO2_USUARIO VARCHAR2(25),
	CONSTRAINT PK_CACB_USUARIO PRIMARY KEY(COD_USUARIO)
);


