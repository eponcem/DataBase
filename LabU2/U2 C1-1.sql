	PARÁMETROS QUE RECIBIRÁ EL PROCEDIMIENTO SEPARADO POR COMAS
)
IS
-- SI REQUIERE VARIABLES LOCALES, VAN ACÁ, SI NO, SE OBVÍA
BEGIN
	CUERPO DEL PROCEDIMIENTO (ACCIONES)
END;
