/*QUISIERA MOSTAR COD_EMPLEADO, APELLIDO, CARGO, DEPARTAMENTO
Y FECHA DE CONTRATACION DE TODOS AQUELLOS EMPLEADOS QUE FUERON
CONTRATADOS DESPUES DEL AÑO 2015, ORDENADO POR FECHA DE CONTRATACION
DE MANERA DESCENDENTE

COMO RESUELVO EL REQUERIMIENTO ORGINALNADO POR DEPARTAMENTO Y LUEGO
POR FECHA DE CONTRATACION, LA ULTIMA DE MANERA DESCENDENTE, PARA TERMINAR
POR APELLIDO.
*/
SELECT EMPLOYEE_ID AS COD_EMPLEADO, LAST_NAME AS APELLIDO, JOB_ID AS CARGO,
DEPARTMENT_ID AS DEPARTAMENTO, HIRE_DATE AS FECHA
FROM OEHR_EMPLOYEES
WHERE HIRE_DATE > '12/31/2015'
ORDER BY DEPARTAMENTO, FECHA DESC, APELLIDO;

