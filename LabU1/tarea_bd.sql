-- TAREA 2
-----------------------------------------------------------------------
/* QUISIERA UN REPORTE CONSTRUIDO DE LA SIGUIENTE FORMA:
COD_TRABAJADOR, APELLIDO, SUELDO ($25,000.00), COMISION ASOCIADA (MOSTRADA CON VALORES NUMERICOS PARA TODOS LOS
TRABAJADORES: 100) Y EN CASO DE QUE NO TENGO COMISION, ESCRIBA EL TEXTO: 'SIN COMISION'
*/

SELECT EMPLOYEE_ID AS "COD_EMPLEADO", LAST_NAME AS "APELLIDO", TO_CHAR(SALARY,'$999,999.99') AS "SALARIO", 
NVL2(COMMISSION_PCT,CONCAT(TO_CHAR(COMMISSION_PCT*100),'%'),'SIN COMISION') AS "COMISION", 
NVL(TO_CHAR(SALARY*(COMMISSION_PCT+1),'$999,999.99'), 'SIN COMISION') AS "ACTUALIZADO"
FROM OEHR_EMPLOYEES;


