-- QUISIERA SABER COD_TRABAJADOR, APELLIDO, NOMBRE_DEPARTAMENTO Y CIUDAD DE TODOS 
-- AQUELLOS TRABAJADORES QUE TENGAN UN SUELDO SUPERIOR AL DE WHALEN

SELECT E.EMPLOYEE_ID AS "COD_TRABAJADOR", E.LAST_NAME AS "APELLIDO", 
	D.DEPARTMENT_NAME AS "DEPARTAMENTO", L.CITY AS "CIUDAD"
FROM OEHR_EMPLOYEES E JOIN OEHR_DEPARTMENTS D ON(E.DEPARTMENT_ID = D.DEPARTMENT_ID)
	JOIN OEHR_LOCATIONS L ON(D.LOCATION_ID = L.LOCATION_ID)
WHERE E.SALARY > (SELECT SALARY
					FROM OEHR_EMPLOYEES
					WHERE UPPER(LAST_NAME) = 'WHALEN');


-- QUISIERA SABER COD_TRABAJADOR, APELLIDO, NOMBRE_DEPARTAMENTO Y CIUDAD DE TODOS 
-- AQUELLOS TRABAJADORES QUE GANEN SUELDOS QUE VARÍEN ENTRE LOS SUELDOS DE NAYER Y 
-- WHALEN

SELECT E.EMPLOYEE_ID AS "COD_TRABAJADOR", E.LAST_NAME AS "APELLIDO", 
	D.DEPARTMENT_NAME AS "DEPARTAMENTO", L.CITY AS "CIUDAD"
FROM OEHR_EMPLOYEES E JOIN OEHR_DEPARTMENTS D ON(E.DEPARTMENT_ID = D.DEPARTMENT_ID)
	JOIN OEHR_LOCATIONS L ON(D.LOCATION_ID = L.LOCATION_ID)
WHERE E.SALARY BETWEEN (SELECT SALARY
						FROM OEHR_EMPLOYEES
						WHERE UPPER(LAST_NAME)= 'NAYER') 
				AND (SELECT SALARY
						FROM OEHR_EMPLOYEES
						WHERE UPPER(LAST_NAME)= 'WHALEN');


-- QUISIERA SABER EL APELLIDO, NOMBRE_CARGO Y SUELDO DE TODOS AQUELLOS TRABAJADORES
-- QUE TENGAN UN CARGO COMO EL DE TAYLOR Y SU SUELDO SEA MAYOR QUE EL DE TAYLOR

SELECT E.LAST_NAME, J.JOB_TITLE, E.SALARY 
FROM OEHR_EMPLOYEES E JOIN OEHR_JOBS J ON (E.JOB_ID = J.JOB_ID)
WHERE E.JOB_ID IN (SELECT JOB_ID
					FROM OEHR_EMPLOYEES
					WHERE UPPER(LAST_NAME) = 'TAYLOR') 
				AND 
				E.SALARY > ALL (SELECT SALARY
							FROM OEHR_EMPLOYEES
							WHERE UPPER(LAST_NAME)= 'TAYLOR');



-- QUISIERA SABER APELLIDO Y PAÍS DE TODOS AQUELLOS TRABAJADORES QUE GANEN MÁS QUE
-- EL SUELDO PROMEDIO DE TODOS LOS TRABAJADORES
SELECT E.LAST_NAME AS "APELLIDO", C1.COUNTRY_NAME AS "PAIS"
FROM OEHR_EMPLOYEES E 
JOIN OEHR_DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
JOIN OEHR_LOCATIONS L ON (D.LOCATION_ID = L.LOCATION_ID) 
JOIN OEHR_COUNTRIES C1 ON (L.COUNTRY_ID = C1.COUNTRY_ID)
WHERE E.SALARY > (SELECT AVG(SALARY) FROM OEHR_EMPLOYEES)  


-- QUISIERA SABER EL NOMBRE DEL DEPARTAMENTO Y EL SUELDO MÍNIMO ASOCIADO POR CADA
-- UNO, SIEMPRE Y CUANDO EL SUELDO MÍNIMO, SEA MAYOR QUE EL SUELDO MÍNIMO DEL 
-- DEPARTAMENTO 80

SELECT D.DEPARTMENT_NAME AS "NOMBRE DEPARTAMENTO", MIN(E.SALARY) AS "SALARIO MINIMO"
FROM OEHR_EMPLOYEES E
JOIN OEHR_DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
GROUP BY D.DEPARTMENT_NAME
HAVING MIN(E.SALARY) > (SELECT MIN(SALARY) FROM OEHR_EMPLOYEES WHERE DEPARTMENT_ID = 80)

-- QUISIERA SABER EL COD_EMPLEADO, APELLIDO, NOMBRE_CARGO Y SUELDO DE TODOS AQUELLOS
-- TRABAJADORES QUE SU SUELDO SEA MENOR QUE ALGÚN SUELDO DEL CARGO 'SA_MAN' Y SU 
-- CARGO SEA DISTINTO A 'SA_MAN'

SELECT E.EMPLOYEE_ID AS "COD EMPLEADO", E.LAST_NAME AS "APELLIDO", J.JOB_TITLE AS "NOMBRE CARGO", E.SALARY AS "SALARIO"
FROM OEHR_EMPLOYEES E
JOIN OEHR_JOBS J ON (E.JOB_ID = J.JOB_ID)
WHERE E.SALARY < ANY(SELECT SALARY FROM OEHR_EMPLOYEES WHERE UPPER(JOB_ID) = 'SA_MAN') 
AND E.JOB_ID NOT IN (SELECT JOB_ID FROM OEHR_EMPLOYEES WHERE UPPER(JOB_ID) = 'SA_MAN')

-- QUISIERA SABER EL COD_EMPLEADO, APELLIDO, NOMBRE_CARGO Y SUELDO DE TODOS AQUELLOS
-- TRABAJADORES QUE SU SUELDO SEA MENOR QUE TODOS LOS SUELDOS DEL CARGO 'SA_MAN' Y 
-- SU CARGO SEA DISTINTO A 'SA_MAN

SELECT E.EMPLOYEE_ID AS "COD EMPLEADO", E.LAST_NAME AS "APELLIDO", 
J.JOB_TITLE AS "NOMBRE CARGO", E.SALARY AS "SALARIO"
FROM OEHR_EMPLOYEES E
JOIN OEHR_JOBS J ON (E.JOB_ID = J.JOB_ID)
WHERE E.SALARY < ALL(SELECT SALARY FROM OEHR_EMPLOYEES WHERE UPPER(JOB_ID) = 'SA_MAN') AND 
E.JOB_ID <> 'SA_MAN'

/*
La gerencia requiere un informe con el código de empleado, 
su nombre completo concatenado en mayúsculas con un espacio de separación (por ejemplo: 'JUAN PEREZ'), 
el nombre de su departamento y una simulación de su salario anual multiplicando el sueldo por 12,
considerando únicamente a los trabajadores cuyo salario sea estrictamente mayor que el 
salario promedio de toda la empresa y 
que pertenezcan a departamentos ubicados en ciudades que no comiencen con la letra 'S', 
ordenando los resultados de mayor a menor según el salario anual proyectado. */

SELECT EMPLOYEE_ID AS "COD EMPLEADO",UPPER(CONCAT(E.FIRST_NAME,CONCAT(' ',E.LAST_NAME))) AS "NOMBRE COMPLETO",
D.DEPARTMENT_NAME AS "NOMBRE DEPARTAMENTO", E.SALARY*12 AS "SALARIO ANUAL"
FROM OEHR_EMPLOYEES E
JOIN OEHR_DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
JOIN OEHR_LOCATIONS L ON (D.LOCATION_ID = L.LOCATION_ID)
WHERE E.SALARY > (SELECT AVG(SALARY) FROM OEHR_EMPLOYEES) AND NOT L.CITY LIKE 'S%' 
ORDER BY (E.SALARY*12) DESC;

-- Se solicita un reporte consolidado por departamento que proyecte el nombre del departamento, 
-- el total de trabajadores contando la clave primaria EMPLOYEE_ID y 
-- la suma total de salarios pagados formateada con signo de dólar y dos decimales, 
-- mostrando únicamente aquellos departamentos que tengan más de 2 trabajadores y 
-- cuyo sueldo mínimo interno sea estrictamente mayor que todos los sueldos de los trabajadores 
-- que desempeñan el cargo 'IT_PROG', 
-- ordenando la salida según el número total de trabajadores de manera descendente.

SELECT D.DEPARTMENT_NAME AS "NOMBRE DEPARTAMENTO", COUNT(E.EMPLOYEE_ID) AS "TOTAL TRABAJADORES", 
TO_CHAR(SUM(E.SALARY),'$999,999.99') AS "SALARIO"
FROM OEHR_EMPLOYEES E
JOIN OEHR_DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
GROUP BY D.DEPARTMENT_NAME
HAVING COUNT(E.EMPLOYEE_ID) > 2 AND MIN(E.SALARY) > ALL(SELECT SALARY FROM OEHR_EMPLOYEES WHERE UPPER(JOB_ID) = 'IT_PROG')
ORDER BY COUNT(E.EMPLOYEE_ID) DESC;


-- Se requiere un reporte jerárquico que presente el código del trabajador, el apellido del trabajador, 
-- el apellido de su jefe directo y la cantidad de semanas trabajadas hasta la fecha actual 
-- calculada mediante la diferencia entre SYSDATE e HIRE_DATE dividida por 7 y truncada sin decimales, 
-- filtrando únicamente a los empleados cuyo sueldo sea menor que algún sueldo de los empleados 
-- con el cargo 'SA_MAN', excluyendo del informe a los propios trabajadores con cargo 'SA_MAN' y 
-- ordenando la lista alfabéticamente por el apellido del trabajador.

SELECT E.EMPLOYEE_ID AS "COD EMPLEADO", E.LAST_NAME AS "APELLIDO TRABAJADOR", M.LAST_NAME AS "APELLIDO EMPLEADO",
TRUNC((SYSDATE - E.HIRE_DATE)/7,0) AS "SEMANAS TRABAJADAS"
FROM OEHR_EMPLOYEES E
JOIN OEHR_EMPLOYEES M ON (E.MANAGER_ID = M.EMPLOYEE_ID)
WHERE E.SALARY < ANY(SELECT SALARY FROM OEHR_EMPLOYEES WHERE UPPER(JOB_ID) = 'SA_MAN')
ORDER BY E.LAST_NAME ASC;

-- Se requiere un informe para Auditoría que presente:
-- • El código del empleado.
-- • El apellido del trabajador.
-- • La fecha de contratación formateada en texto legible utilizando TO_CHAR (por ejemplo: '21-09-2026').
-- • El nombre de su departamento.
-- • Una simulación de su salario incrementado en un 15% redondeado a cero decimales mediante ROUND.
-- Considerando únicamente a los trabajadores que hayan sido contratados después del 31 de diciembre del año 2005 y 
-- cuya ciudad de trabajo sea 'Seattle' o 'Southlake'.
-- Ordenando el resultado de manera descendente según el salario incrementado.

SELECT E.EMPLOYEE_ID AS "COD EMPLEADO", E.LAST_NAME AS "APELLIDO", 
TO_CHAR(E.HIRE_DATE,'DD"-"MM"-"YYYY') AS "FECHA DE CONTRATACION", D.DEPARTMENT_NAME AS "NOMBRE DEPARTAMENTO",
ROUND((E.SALARY*115)/100,0) AS "SIMULACION SALARIO"
FROM OEHR_EMPLOYEES E
JOIN OEHR_DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
JOIN OEHR_LOCATIONS L ON (D.LOCATION_ID = L.LOCATION_ID)
WHERE HIRE_DATE > '12/31/2005' AND INITCAP(L.CITY) IN ('Seattle','Southlake')
ORDER BY ROUND((E.SALARY*115)/100,0) DESC;

-- Se solicita un reporte presupuestario por departamento que proyecte el nombre del departamento, 
-- el salario promedio de sus trabajadores redondeado a dos decimales y el conteo total de empleados 
-- utilizando la clave primaria EMPLOYEE_ID, filtrando únicamente aquellos departamentos que tengan más 
-- de 3 trabajadores y cuyo salario promedio interno sea estrictamente mayor que el salario promedio 
-- general de toda la empresa, ordenando la salida de mayor a menor según el promedio de sueldos del 
-- departamento.


SELECT D.DEPARTMENT_NAME AS "NOMBRE DEPARTAMENTO", ROUND(AVG(E.SALARY),2) AS "SALARIO", COUNT(E.EMPLOYEE_ID) AS "CANTIDAD DE EMPLEADOS"
FROM OEHR_EMPLOYEES E
JOIN OEHR_DEPARTMENTS D ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
GROUP BY D.DEPARTMENT_NAME
HAVING COUNT(E.DEPARTMENT_ID) > 3 AND AVG(E.SALARY) > (SELECT AVG(SALARY) FROM OEHR_EMPLOYEES)
ORDER BY ROUND(AVG(E.SALARY),2) DESC;